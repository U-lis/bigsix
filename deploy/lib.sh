#!/usr/bin/env bash
# 배포 스크립트들이 공유하는 함수. 여기 있는 것은 전부 tests/deploy 로 검증된다.

# ref 가 가리키는 커밋 SHA.
#
# annotated 태그를 그냥 rev-parse 하면 커밋이 아니라 태그 객체 SHA 가 나온다.
# 서버는 체크아웃으로 커밋에 정확히 서므로, 그 값으로 대조하면 올바르게 배포하고도
# 어긋난 것으로 판정된다. v0.1.0 배포에서 실제로 그랬고, 검증이 목적인 스크립트가
# HTTP 검증과 프리캐시 대조를 통째로 건너뛰고 실패로 끝났다.
resolve_commit() {
	# --verify 가 없으면 해석에 실패했을 때 입력 문자열을 그대로 뱉고 성공한 척한다.
	# 그 값이 SHA 대조로 흘러가면 "어긋남" 이라는 엉뚱한 진단이 나온다.
	git rev-parse --verify --quiet "$1^{commit}"
}
